'use strict';
const assert=require('node:assert/strict');
const {change,identity,authorized,cleanClub,handle}=require('../functions/roster-cloud');
const {plan,same}=require('../js/roster-cloud');
assert(same({a:1,b:{d:2,c:3}},{b:{c:3,d:2},a:1}));
const club={id:'club-test',name:'E2E클럽',members:[{name:'E2E가',gender:'여',grade:'E',level:.7,skillStep:-1,ageGroup:'50대',isClubOfficial:true,skillAdjustmentMeta:{source:'quiz'},customNote:'retain'}]};
const doc={owner:'owner',club,revision:1,updatedAt:100,editors:{editor:true}};
const command={action:'save',revision:1,operationId:'operation0000001',club:{...club,name:'E2E클럽 수정'}};
assert.throws(()=>identity(null),{code:'unauthenticated'});
assert.throws(()=>identity({uid:'u',token:{email_verified:false}}),{code:'unauthenticated'});
assert.throws(()=>identity({uid:'u',token:{email_verified:true,firebase:{sign_in_provider:'anonymous'}}}),{code:'unauthenticated'});
assert.equal(identity({uid:'u',token:{email_verified:true}}),'u');
assert.equal(authorized(doc,'stranger'),false);
assert.throws(()=>change(doc,'stranger',command,200),{code:'permission-denied'});
const next=change(doc,'editor',command,200);
assert.equal(next.revision,2);assert.equal(next.history[0].club.name,club.name);
assert.deepEqual(next.club.members,club.members);
assert.deepEqual(change(next,'editor',command,201),next);
assert.throws(()=>change(next,'owner',{...command,operationId:'operation0000002'},202),{code:'aborted'});
assert.throws(()=>change(next,'editor',{...command,club},202));
assert.throws(()=>change(doc,'owner',{...command,club:{...club,members:[]}},202));
assert.throws(()=>change(doc,'owner',{...command,club:{...club,id:'other'}},202));
const restored=change(next,'owner',{action:'restore',revision:2,target:1,operationId:'restore00000001'},210);
assert.deepEqual(restored.club,club);assert.equal(restored.revision,3);
assert.throws(()=>change(restored,'editor',command,211),{code:'aborted'});
assert.equal(cleanClub({...club,token:'secret'}).token,undefined);
assert.equal(plan(club,{base:club}),'clean');
assert.equal(plan(command.club,{base:club}),'save');
assert.equal(plan(club,{base:club,pending:command}),'retry');
assert.equal(plan(club,{base:club,conflict:true}),'conflict');
assert.equal(plan({...club,members:[]},{base:club}),'empty');
assert.equal(plan(null,{base:club}),'missing');
let current=doc;
for(let i=0;i<20;i++)current=change(current,'owner',{...command,revision:current.revision,operationId:'rolling000000'+i},300+i);
assert.equal(current.history.length,10);
// Real endpoint orchestration with an atomic in-memory database.
const data=new Map();
const snapshot=v=>({val:()=>v?structuredClone(v):null});
const db={ref(path){return {async once(){return snapshot(data.get(path));},child(id){return db.ref(path+'/'+id);},async set(v){data.set(path,structuredClone(v));},async transaction(fn){const value=fn(structuredClone(data.get(path)||null));if(value===undefined)return {committed:false,snapshot:snapshot(data.get(path))};data.set(path,structuredClone(value));return {committed:true,snapshot:snapshot(value)};}};}};
(async()=>{
  const auth={uid:'owner',token:{email_verified:true}};
  const created=await handle(db,auth,{action:'create',club},100);
  assert.equal(created.revision,1);
  assert.equal((await handle(db,auth,{action:'list'})).clubs.length,1);
  assert.equal((await handle(db,auth,{action:'create',club:{...club,name:'stale'}})).club.name,club.name);
  await assert.rejects(handle(db,{uid:'other',token:{email_verified:true}},{action:'read',id:created.id}),{code:'permission-denied'});
  const results=await Promise.allSettled([handle(db,auth,{...command,id:created.id}),handle(db,auth,{...command,id:created.id,operationId:'concurrent00002'})]);
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
  assert.equal(results.filter(r=>r.status==='rejected')[0].reason.code,'aborted');
  console.log('roster cloud: identity, isolation, stale writes, retries, concurrent save, history and offline guards PASS');
})().catch(e=>{console.error(e);process.exit(1);});

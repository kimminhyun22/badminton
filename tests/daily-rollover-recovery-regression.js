'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const {flushPendingArchives} = require('../functions/daily-archive');
const html = fs.readFileSync(require('path').join(__dirname,'../checkin.html'),'utf8');
const source = html.slice(html.indexOf('function sessionRolloverBlockReason(){'),html.indexOf('function sessionSetupEligible(){'));
const now = 1800000000000, hour = 3600000;
const context = vm.createContext({Date:{now:()=>now},session:{capabilities:{officialSessionRolloverV1:true},event:{operationStarted:true,operationStartedAt:now-5*hour,active:[],next:[]}}});
vm.runInContext(source,context);
const eligible=()=>vm.runInContext('sessionRolloverEligible()',context);
assert(eligible());
context.session.event.active=[{startedAt:now-5*hour}];
assert(eligible(),'old unfinished court must not block rollover');
context.session.event.active=[{startedAt:now-4*hour}];
assert(eligible(),'four-hour boundary matches server');
context.session.event.active.push({startedAt:now-hour});
assert(!eligible(),'one recent court blocks rollover');
context.session.event.active=[];
context.session.event.next=[{id:'queued'}];
assert(!eligible(),'queued games must be cleared first');
context.session.event.next=[];
context.session.event.operationStartedAt=now-hour;
assert(!eligible());

(async()=>{
  const entry={at:now,completedLog:[{seq:1,t1:['E2EA','E2EB'],t2:['E2EC','E2ED']}]};
  const pending={op1:entry};
  let attempts=0, written;
  const db={ref:()=>({update:async changes=>{attempts++;if(attempts===1)throw Error('transient');written=changes;}})};
  await flushPendingArchives(db,'checkin_DABCDEFG',pending);
  assert.equal(attempts,2);
  assert.deepStrictEqual(written[`liveArchive/checkin_DABCDEFG/${now}`],entry);
  assert.strictEqual(written['live/checkin_DABCDEFG/pendingArchives/op1'],null);
  assert.deepStrictEqual(pending.op1,entry,'source survives until atomic acknowledgment');
  attempts=0;
  await assert.rejects(flushPendingArchives({ref:()=>({update:async()=>{attempts++;throw Error('offline');}})},'checkin_DABCDEFG',pending));
  assert.equal(attempts,2,'bounded retry');
  assert.deepStrictEqual(pending.op1,entry);
  await flushPendingArchives(db,'checkin_DABCDEFG',pending);
  assert.equal(Object.keys(written).length,2,'replaying writes same deterministic archive, no duplicate');
  const before=attempts;
  await flushPendingArchives(db,'checkin_DABCDEFG',{});
  await flushPendingArchives(db,'team_session',pending);
  assert.equal(attempts,before);
  console.log('PASS rollover boundary, pending archive recovery, atomic acknowledgment, bounded retry, idempotent replay');
})().catch(error=>{console.error(error);process.exit(1);});

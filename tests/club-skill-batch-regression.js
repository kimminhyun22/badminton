'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm'),B=require('../js/club-skill-batch');
const members=[0,1,2].map(i=>({name:'E2E'+i,grade:'C',gender:'남',ageGroup:'40대',level:4,skillStep:0,isClubOfficial:i===0}));
const state={clubs:[{id:'test',members},{id:'other',members:[{name:'E2E다른클럽'}]}],extra:'keep'};
const items=members.map((original,i)=>({id:'p'+i,original,step:i===2?-1:1}));
const original=JSON.stringify(state);
const applied=B.prepare(state,'test',items,'review','batch');
assert.equal(applied.count,3);assert.equal(JSON.stringify(state),original);
assert.equal(applied.state.clubs[0].members[0].level,4.2);
assert.equal(applied.state.clubs[0].members[2].level,3.8);
assert.equal(applied.state.clubs[0].members[0].isClubOfficial,true);
assert.deepEqual(applied.state.clubs[1],state.clubs[1]);
assert.throws(()=>B.prepare(applied.state,'test',items,'review','repeat'),'replay cannot overwrite');
assert.throws(()=>B.prepare(state,'test',[items[0],{...items[1],original:{...items[1].original,grade:'B'}}],'review','stale'));
assert.equal(JSON.stringify(state),original,'all or nothing for stale member');
assert.throws(()=>B.prepare(state,'test',[{...items[0],step:3}],'review','bad'));
const club=applied.state.clubs[0];
assert(B.baseline(club,'review','p0',club.members[0]));
club.members[1].skillStep=2;club.members[1].level=4.4;
assert.equal(B.baseline(club,'review','p1',club.members[1]),null,'manual edit protected');
const undone=B.undo(applied.state,'test','batch');
assert.equal(undone.count,2);assert.equal(undone.skipped,1);
assert.equal(undone.state.clubs[0].members[0].level,4);
assert.equal(undone.state.clubs[0].members[1].level,4.4);
assert.throws(()=>B.undo(undone.state,'test','batch'));
const next=B.prepare(applied.state,'test',[{id:'p0',original:club.members[0],step:0}],'review','batch2');
assert.equal(next.state.clubs[0].members[0].level,4,'new proposal is absolute, not double-added');
assert.equal(B.undo(next.state,'test','batch2').state.clubs[0].members[0].level,4.2);
const source=fs.readFileSync('js/club-skill-batch.js','utf8'),ctx={module:{exports:{}}};
vm.runInNewContext(source.replace('!same(matches[0],e.after)','false'),ctx);
assert.throws(()=>assert.equal(ctx.module.exports.undo(applied.state,'test','batch').state.clubs[0].members[1].level,4.4),'manual-protection mutation caught');
const review=fs.readFileSync('js/club-skill-review.js','utf8');
const frag=review.slice(review.indexOf('  function resultState('),review.indexOf('  function renderOwner('));
const env={window:{KokSkillBatch:B}};vm.runInNewContext(frag+';this.row=proposalRow;',env);
const own={id:'review',snapshots:members};
let row=env.row({id:'p0',current:0,step:0,ready:false,reviewed:true,opponents:4},own,club);
assert.equal(row.state.key,'ready','additional answers may propose return to original after batch');
row=env.row({id:'p1',current:0,step:1,ready:true,reviewed:true,opponents:4},own,club);
assert.equal(row.state.key,'changed','manual adjustment not overwritten by further answers');
for(const file of ['index.html','team.html','skill-review.html'])assert(fs.readFileSync(file,'utf8').includes('js/club-skill-batch.js'));
console.log('skill batch: atomic plan, stale/replay protection, bounded values, undo/manual exclusion, continuing survey, mutation passed');

'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm');
const C=require('../functions/skill-calibration-core'),B=require('../js/club-skill-batch'),S=require('../functions/skill-calibration');
const qctx={};vm.runInNewContext(fs.readFileSync('js/match-quality.js','utf8'),qctx);const Q=qctx.KokMatchQuality,E=require('../functions/daily-server-matchmaker');
const raw=[{name:'E2E선배',grade:'A',gender:'여',ageGroup:'60대+',level:5},{name:'E2E후배',grade:'A',gender:'남',ageGroup:'20대',level:6},{name:'E2E초심',grade:'E',gender:'남',ageGroup:'40대',level:2}];
const players=C.players(raw),questions=C.pairs(players),votes={e0:{p0_p1:'a',p0_p2:'a',p1_p2:'a'}};
const p=C.proposals(players,questions,votes);
assert(p[0].skillRating>p[1].skillRating&&p[1].skillRating>p[2].skillRating,'comparison order replaces demographic order');
assert(p.every(p=>p.ready),'two opponents suffice, no min-three gate');
const wide=C.proposals(players,questions,Object.fromEntries(Array.from({length:100},(_,i)=>['u'+i,votes.e0])));
assert(wide[0].skillRating-wide[2].skillRating>3,'evidence may exceed old correction cap');
const mixed=C.players(raw.map(p=>({...p,gender:'남',ageGroup:'20대',level:undefined})));
const alt=C.proposals(mixed,C.pairs(mixed),votes);
assert(Math.abs((alt[0].skillRating-alt[1].skillRating)-(p[0].skillRating-p[1].skillRating))<.002,'demographic profile cannot reverse learned differences');
const original=JSON.stringify(votes);
const state={clubs:[{id:'c',name:'E2E클럽',members:raw}]};
const applied=B.prepare(state,'c',p.map((p,i)=>({id:p.id,original:raw[i],step:p.step,skillRating:p.skillRating})),'r','b');
const members=applied.state.clubs[0].members;
for(const m of members){
 assert.equal(Q.effectiveLevel(m),m.skillRating);assert.equal(E.effectiveLevel(m),m.skillRating);
 for(const gender of ['남','여','M','F'])for(const ageGroup of ['20대','60대+'])assert.equal(Q.effectiveLevel({...m,gender,ageGroup}),m.skillRating);
 assert.equal(Q.skillBreakdown(m).age,0);assert.equal(Q.skillBreakdown(m).gender,0);
}
const reapplied=C.proposals(C.players(members),questions,votes,players);
assert(reapplied.every((q,i)=>q.skillRating===p[i].skillRating&&!q.ready),'no compounding or rebase drift');
const undo=B.undo(applied.state,'c','b');assert.deepEqual(undo.state.clubs[0].members,raw.map(m=>({...m,skillStep:0})));
assert.equal(JSON.stringify(votes),original);
const sparse=C.proposals(players,questions,{e0:{p0_p1:'a'}});
assert(sparse[0].ready&&!sparse[0].connected);assert(!sparse[2].ready);
assert.equal(sparse[2].skillRating,players[2].base,'uncompared member keeps initial estimate');
const disagreement=C.proposals(players,questions,{e0:{p0_p1:'a'},e1:{p0_p1:'b'}});
assert.equal(disagreement[0].skillRating,disagreement[1].skillRating,'split evidence participates instead of being dropped');
const session={id:'s',clubName:'E2E',players,questions:[questions[0]],votes,expiresAt:Date.now()+1e5};
assert.equal(S.project(session,'owner').questions.length,3,'old session gains cross-profile pairs');
assert.equal(S.project(session,'owner').count,3);assert.deepEqual(S.project(session,'shared').proposals,[]);
assert(S.project(session,'shared').players.every(p=>p.skillRating===undefined),'participant privacy boundary retained');
const source=fs.readFileSync('js/match-quality.js','utf8'),ctx={module:{exports:{}}};
vm.runInNewContext(source.replace('if(Number.isFinite(player?.skillRating))return player.skillRating;',''),ctx);
assert.notEqual(ctx.KokMatchQuality.effectiveLevel({...members[0],ageGroup:'20대'}),members[0].skillRating,'mutation catches demographics reapplied');
const broken={module:{exports:{}}};vm.runInNewContext(fs.readFileSync('functions/skill-calibration-core.js','utf8').replace('wins:counts.a+counts.tie/2','wins:counts.b+counts.tie/2'),broken);
assert(broken.module.exports.proposals(players,questions,votes)[0].skillRating<p[1].skillRating,'direction mutation caught');
console.log('final skill: accumulated votes, demographics invariant, no cap/min3, idempotent reuse, sparse groups, privacy, storage/undo, server parity and mutations passed');

const transfer=require('../js/roster-transfer');
const packet=transfer.packet(applied.state.clubs[0]);
assert.equal(packet.clubs[0].members[0].skillRating,members[0].skillRating,'independent roster transfer preserves rating');

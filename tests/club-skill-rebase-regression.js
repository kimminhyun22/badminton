'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm');
const C=require('../functions/skill-calibration-core'),B=require('../js/club-skill-batch');
const {project,handle}=require('../functions/skill-calibration'),crypto=require('crypto');
const members=Array.from({length:5},(_,i)=>({name:'E2E'+i,grade:'C',gender:'남',ageGroup:'40대',skillStep:0,level:4}));
const players=C.players(members),questions=C.pairs(players),answers=Object.fromEntries(questions.map(q=>[q.id,q.a==='p0'?'a':'tie']));
const key='1'.repeat(32),invite='2'.repeat(32),hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const s={id:'3'.repeat(32),clubName:'E2E',players,questions,votes:{e0:answers},owner:hash(key),invites:[hash(invite)],expiresAt:Date.now()+86400000};
const before=JSON.stringify(s),club={id:'test',members:structuredClone(members)},own={id:s.id,snapshots:members};
club.members[0].skillStep=2;club.members[0].level=4.4;
const baselines=B.reviewBaselines(own,club);
const old=project(s,'owner'),next=project(s,'owner',baselines);
assert.equal(old.proposals[0].step,1);
assert.equal(next.proposals[0].current,2);assert.equal(next.proposals[0].step,2,'manual baseline retained when ordinal evidence already fits');
assert.equal(next.proposals[0].ready,false);assert.equal(next.proposals[0].basis.level,4.4);
assert.deepEqual(project(s,'owner',baselines),next,'re-read does not compound adjustments');
assert.equal(JSON.stringify(s),before,'neither votes nor survey snapshots are rewritten');
assert.throws(()=>project(s,'e0',baselines));
assert.throws(()=>project(s,'owner',[baselines[0],baselines[0]]));
assert.throws(()=>project(s,'owner',[{...baselines[0],id:'missing'}]));
assert.throws(()=>project(s,'owner',[{...baselines[0],level:9}]));
assert.throws(()=>project(s,'owner',[{...baselines[0],grade:'B',level:5.4}]));
const changed=structuredClone(club);changed.members[0].grade='B';changed.members[0].level=5.4;
assert(!B.reviewBaselines(own,changed).some(p=>p.id==='p0'));
const reversed=structuredClone(s);reversed.votes.e1=Object.fromEntries(questions.map(q=>[q.id,q.a==='p0'?'b':'tie']));reversed.votes.e2=reversed.votes.e1;
const updated=project(reversed,'owner',baselines).proposals[0];
assert(updated.step<2&&updated.ready,'new evidence may propose change from manual baseline');
const source=fs.readFileSync('js/club-skill-review.js','utf8');
const fragment=source.slice(source.indexOf('  function resultState('),source.indexOf('  function renderOwner('));
const ctx={window:{KokSkillBatch:B}};vm.runInNewContext(fragment+';this.row=proposalRow;',ctx);
assert.equal(ctx.row(next.proposals[0],own,club).state.key,'same');
assert.equal(ctx.row(updated,own,club).state.key,'ready');
const raced=structuredClone(club);raced.members[0].skillStep=1;raced.members[0].level=4.2;
assert.equal(ctx.row(updated,own,raced).state.key,'changed','late response does not approve stale baseline');
assert.equal(ctx.row(updated,own,changed).state.key,'changed');
const applied=B.prepare({clubs:[club]},'test',[{id:'p0',original:club.members[0],step:updated.step}],s.id,'new');
assert.equal(applied.state.clubs[0].members[0].skillStep,updated.step);
assert.equal(B.undo(applied.state,'test','new').state.clubs[0].members[0].skillStep,2,'undo returns to manual baseline');
const serverSource=fs.readFileSync('functions/skill-calibration.js','utf8'),mutated={module:{exports:{}},require:n=>n==='./skill-calibration-core'?C:require(n)};
vm.runInNewContext(serverSource.replace('effective=s.players.map(p=>byId.get(p.id)||p)','effective=s.players'),mutated);
assert.throws(()=>assert.equal(mutated.module.exports.project(s,'owner',baselines).proposals[0].current,2),'ignoring baseline mutation caught');
(async()=>{
  const db={ref:()=>({once:async()=>({val:()=>structuredClone(s)})})};
  const result=await handle(db,{action:'read',id:s.id,key,baselines},'E2E');
  assert.equal(result.proposals[0].current,2);
  await assert.rejects(handle(db,{action:'read',id:s.id,key:invite,baselines},'E2E'));
  console.log('skill rebase: manual prior, new evidence, no double addition, stale/demographic/role rejection, immutable read, undo, mutation passed');
})().catch(e=>{console.error(e);process.exitCode=1;});

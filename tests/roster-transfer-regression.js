'use strict';
const assert=require('assert'),fs=require('fs');
const {clean,packet,append,store}=require('../js/roster-transfer');
const member={name:'E2E회원',gender:'여',grade:'E',ageGroup:'40대',level:0.8,skillStep:4,isClubOfficial:true,isTemporaryOfficial:true,grantToken:'secret',skillCalibration:{token:'secret'},memberId:'old-member'};
const club={id:'old-club',name:'E2E클럽',members:[member],owner:'old-owner',invite:'secret'};
const transferred=packet(club);
assert.equal(transferred.clubs[0].members[0].skillStep,4);
assert.equal(transferred.clubs[0].members[0].level,0.8);
assert(!JSON.stringify(transferred).includes('secret'));
assert(!JSON.stringify(transferred).includes('old-'));
assert(!JSON.stringify(transferred).includes('isTemporaryOfficial'));
assert.equal(member.grantToken,'secret','source not mutated');
const before={_lvVersion:2,clubs:[club]};let id=0;
const copied=append(before,clean(transferred),new Set(),()=>String(++id));
assert.equal(copied.clubs.length,2);
assert.deepStrictEqual(copied.clubs[0],club);
assert.notEqual(copied.clubs[1].name,club.name);
assert.notEqual(copied.clubs[1].id,club.id);
assert.notEqual(copied.clubs[1].members[0].memberId,member.memberId);
assert.strictEqual(copied.clubs[1].members[0].isClubOfficial,false,'old official not silently inherited');
assert.equal(append(before,clean(transferred),new Set(['0:0']),()=>String(++id)).clubs[1].members[0].isClubOfficial,true);
assert.equal(append(copied,clean(transferred),new Set(),()=>String(++id)).clubs.length,3);
const long={...club,name:'가'.repeat(80)};
assert(append({clubs:[long]},clean({clubs:[long]}),new Set(),()=>String(++id)).clubs[1].name.length<=80);
assert.throws(()=>append({clubs:Array(10).fill(club)},clean(transferred),new Set(),()=>''));
assert.throws(()=>clean({clubs:[{...club,members:[{...member,skillStep:5}]}]}));
assert.throws(()=>clean({clubs:[{...club,members:[{...member,ageGroup:''}]}]}));
assert.throws(()=>clean({clubs:[{...club,members:[{...member,gender:''}]}]}));
assert.throws(()=>clean({kind:'minton-roster-transfer',version:99,clubs:[club]}));
const values=new Map([['badminton_rosters_v1',JSON.stringify(before)],['minton_roster_cloud_v1_uid','original-cloud-binding'],['kokmatch_daily_v1','active-game']]);
const storage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)};
const expected=storage.getItem('badminton_rosters_v1');
assert.throws(()=>store(storage,'stale',copied));
store(storage,expected,copied);
assert.equal(storage.getItem('badminton_rosters_v1_before_transfer'),expected);
assert.equal(storage.getItem('minton_roster_cloud_v1_uid'),'original-cloud-binding');
assert.equal(storage.getItem('kokmatch_daily_v1'),'active-game');
assert.throws(()=>store({getItem:()=>expected,setItem:()=>{throw Error('quota');}},expected,copied));
for(const f of ['index.html','team.html']){
 const html=fs.readFileSync(f,'utf8');
 assert(html.includes('js/roster-transfer.js')&&html.includes('css/roster-transfer.css'));
 assert(html.includes('openRosterTransfer()')&&html.includes('importRosterTransfer(event)'));
}
for(const f of ['js/daily.js','js/team.js'])assert(fs.readFileSync(f,'utf8').includes('return window.importRosterTransfer(evt);'));
console.log('PASS independent roster transfer, explicit officials, skill preservation, credential isolation, storage/conflict protection, both modes');
